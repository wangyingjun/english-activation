export function phrasesForDate(iso: string, n = 8): Phrase[] {
  const day = Date.parse(`${iso}T00:00:00+08:00`);
  const seed = Number.isFinite(day) ? Math.floor(day / 86400000) : 0;
  const start = ((seed % PHRASES.length) + PHRASES.length) % PHRASES.length;
  const out: Phrase[] = [];
  for (let i = 0; i < Math.min(n, PHRASES.length); i++) {
    out.push(PHRASES[(start + i) % PHRASES.length]);
  }
  return out;
}

